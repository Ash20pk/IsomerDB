#!/bin/bash
# The licenses of the libraries compiled into each service's binary, one file per image, in
# licenses/third-party/ (the operator's in operator/THIRD_PARTY_LICENSES, inside its build
# context). The images copy them in. Run after changing a Cargo.lock or go.sum, and
# commit the result; --check (CI) fails if they are out of date.
#
# Needs cargo-about (cargo install --locked cargo-about --features cli) and go-licenses
# (go install github.com/google/go-licenses/v2@v2.0.1).
set -euo pipefail
cd "$(dirname "$0")/.."

out=licenses/third-party
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for svc in api edge embedder; do
  (cd "services/$svc" && cargo about generate --locked -c ../../$out/about.toml ../../$out/about.hbs -o "$tmp/isomer-$svc.txt")
done

# Go: each module's license files, as go-licenses finds them, one after another.
(cd operator && GOOS=linux GOARCH=amd64 GOFLAGS=-mod=mod go-licenses save ./... --save_path "$tmp/go" --ignore github.com/Ash20pk/IsomerDB >/dev/null 2>&1)
{
  echo "Third-party software in the IsomerDB operator, and its licenses."
  echo "Generated by scripts/third-party-licenses.sh (go-licenses); do not edit."
  find "$tmp/go" -type f | LC_ALL=C sort | while read -r f; do
    rel=${f#"$tmp/go/"}
    echo
    echo "================================================================================"
    echo "${rel%/*}: ${f##*/}"
    echo "--------------------------------------------------------------------------------"
    cat "$f"
  done
} > "$tmp/isomerdb-operator.txt"

if [ "${1:-}" = "--check" ]; then
  stale=0
  for f in "$tmp"/*.txt; do
    dest="$out/${f##*/}"; [ "${f##*/}" = isomerdb-operator.txt ] && dest=operator/THIRD_PARTY_LICENSES
    cmp -s "$f" "$dest" || { echo "out of date: $dest"; stale=1; }
  done
  [ "$stale" = 0 ] && echo "third-party licenses are up to date"
  exit "$stale"
fi
mv "$tmp/isomerdb-operator.txt" operator/THIRD_PARTY_LICENSES
cp "$tmp"/*.txt "$out/"
ls -l "$out"/*.txt operator/THIRD_PARTY_LICENSES
