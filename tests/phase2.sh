#!/bin/bash
# Phase 2 acceptance test: primary mode. Cutover from attach, sync projections over sharded
# tables, cache projections, read-your-writes from SQL and from MongoDB drivers, the auditor.
#
#   docker compose --profile attach up -d && ./tests/phase2.sh
set -euo pipefail
cd "$(dirname "$0")/.."

ISO="docker compose exec -T -e PGOPTIONS=-cclient_min_messages=warning db psql -U postgres -d postgres -X -q -t -A -v ON_ERROR_STOP=1"
APP="docker compose exec -T -e PGOPTIONS=-cclient_min_messages=warning db psql -U app -d postgres -X -q -t -A -v ON_ERROR_STOP=1"
SRC="docker compose exec -T source psql -U postgres -d postgres -X -q -t -A -v ON_ERROR_STOP=1"
NET="$(basename "$PWD" | tr '[:upper:]' '[:lower:]')_default"
MONGO=(docker run --rm --network "$NET" mongo:8 mongosh
       "mongodb://isomer:isomer@gateway:10260/?tls=true&tlsAllowInvalidCertificates=true" --quiet)
CONN="host=source port=5432 dbname=postgres user=postgres password=source"
BACK="host=db port=5432 dbname=postgres user=postgres password=isomer"

pass() { printf '  ok   %s\n' "$1"; }
fail() { printf '  FAIL %s\n       expected: %s\n       got:      %s\n' "$1" "$2" "$3"; exit 1; }
expect() { [ "$3" = "$2" ] && pass "$1" || fail "$1" "$2" "$3"; }
contains() { case "$3" in *"$2"*) pass "$1";; *) fail "$1" "...$2..." "$3";; esac; }
eventually() {
  local name=$1 want=$2 cmd=$3 timeout=$(( ${4:-15} * ${ISOMER_TIMEOUT_SCALE:-1} )) got="" start=$SECONDS
  while (( SECONDS - start < timeout )); do
    got=$(eval "$cmd" 2>/dev/null || true)
    [ "$got" = "$want" ] && { pass "$name ($(( SECONDS - start ))s)"; return; }
    sleep 0.5
  done
  fail "$name (after ${timeout}s)" "$want" "$got"
}
mongo_eval() { "${MONGO[@]}" --eval "$1" 2>&1 | tail -1; }

echo "== reset"
$ISO -c "SELECT isomer.drop_projection(name) FROM isomer.projections" >/dev/null
$ISO -c "SELECT isomer.detach(name, drop_tables => true) FROM isomer.attachments WHERE status <> 'cutover'" >/dev/null
$ISO -c "DELETE FROM isomer.attachments; DELETE FROM isomer.events; DELETE FROM isomer.drift_samples; DELETE FROM isomer.audit_stats" >/dev/null
for sub in $($ISO -c "SELECT subname FROM pg_subscription WHERE subname LIKE 'isomer_%'"); do
  $ISO -c "ALTER SUBSCRIPTION $sub DISABLE" -c "ALTER SUBSCRIPTION $sub SET (slot_name = NONE)" -c "DROP SUBSCRIPTION $sub" >/dev/null
done
$ISO <<'SQL' >/dev/null
DROP PUBLICATION IF EXISTS isomer_rollback_crm;
SELECT pg_drop_replication_slot(slot_name) FROM pg_replication_slots WHERE slot_name LIKE 'isomer_rollback_%' AND NOT active;
DROP SCHEMA IF EXISTS crm, dist CASCADE;
DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app') THEN DROP OWNED BY app; DROP ROLE app; END IF; END $$;
SELECT cron.alter_job(jobid, active => true) FROM cron.job WHERE jobname = 'isomer-drain';
SQL
$SRC <<'SQL' >/dev/null
SET default_transaction_read_only = off;
ALTER DATABASE postgres RESET default_transaction_read_only;
DROP SUBSCRIPTION IF EXISTS isomer_rollback_crm;
SQL
$SRC <<'SQL'
SET default_transaction_read_only = off;
DROP PUBLICATION IF EXISTS isomer_crm;
SELECT pg_drop_replication_slot(slot_name) FROM pg_replication_slots WHERE slot_name = 'isomer_crm';
DROP SCHEMA IF EXISTS crm CASCADE;
CREATE SCHEMA crm;
CREATE TABLE crm.accounts (id bigserial PRIMARY KEY, name text NOT NULL, plan text NOT NULL DEFAULT 'free');
CREATE TABLE crm.tickets  (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id bigint NOT NULL,
                           subject text, status text NOT NULL DEFAULT 'open', opened_at timestamptz NOT NULL DEFAULT now());
INSERT INTO crm.accounts (name) SELECT 'account ' || g FROM generate_series(1, 20) g;
INSERT INTO crm.tickets (account_id, subject) SELECT 1 + g % 20, 'ticket ' || g FROM generate_series(1, 50) g;
SQL

echo "== attach, then refuse sync while attached"
$ISO -c "SELECT count(*) FROM isomer.attach('crm', '$CONN', schemas => '{crm}')" >/dev/null
eventually "attached and copied" "2/2" "$ISO -c \"SELECT tables_ready || '/' || tables_total FROM isomer.attachment_status('crm')\"" 30
$ISO <<'SQL' >/dev/null
SELECT isomer.create_projection(
  name => 'account_view', kind => 'document', key => 'id', database => 'crm', lag => '2 seconds',
  query => $q$ SELECT a.id, jsonb_build_object('name', a.name, 'plan', a.plan,
              'open_tickets', (SELECT count(*) FROM crm.tickets t WHERE t.account_id = a.id AND t.status = 'open')) AS doc
              FROM crm.accounts a $q$,
  sources => '{"crm.accounts": "id", "crm.tickets": "account_id"}');
SQL
out=$($ISO -c "SELECT isomer.alter_projection('account_view', freshness => 'sync')" 2>&1 || true)
contains "sync refused while attached" "attached from another database" "$out"

echo "== FR-A10/FR-P1 cutover to primary, with rollback replication"
$SRC -c "INSERT INTO crm.tickets (account_id, subject) VALUES (3, 'written just before cutover')"
steps=$($ISO -c "SELECT string_agg(step, ' > ' ORDER BY ord) FROM isomer.cutover('crm', rollback_conninfo => '$BACK') WITH ORDINALITY AS c(step, detail, ord)")
expect "cutover runs every step" "freeze source > catch up > sequences > defaults > stop replication > rollback replication > done" "$steps"
expect "the last pre-cutover write arrived" "1" "$($ISO -c "SELECT count(*) FROM crm.tickets WHERE subject = 'written just before cutover'")"
expect "attachment is cut over" "cutover" "$($ISO -c "SELECT status FROM isomer.attachments WHERE name = 'crm'")"
src_last=$($SRC -c "SELECT last_value FROM crm.accounts_id_seq")
expect "serial column continues from the source's sequence" "$((src_last + 1))" \
  "$($ISO -c "INSERT INTO crm.accounts (name) VALUES ('first account written to IsomerDB') RETURNING id")"
tickets_last=$($SRC -c "SELECT max(id) FROM crm.tickets")
expect "identity column continues too" "$((tickets_last + 1))" \
  "$($ISO -c "INSERT INTO crm.tickets (account_id, subject) VALUES (1, 'after cutover') RETURNING id")"
expect "column defaults were copied" "free|open" \
  "$($ISO -c "SELECT a.plan || '|' || t.status FROM crm.accounts a, crm.tickets t WHERE a.name = 'first account written to IsomerDB' AND t.subject = 'after cutover'")"
eventually "rollback replication becomes active" "active" \
  "$ISO -c \"SELECT rollback_status FROM isomer.attachments WHERE name = 'crm'\"" 25
$ISO -c "INSERT INTO crm.tickets (account_id, subject) VALUES (2, 'replicated back')" >/dev/null
eventually "IsomerDB's writes flow back to the source (rollback replica)" "1" \
  "$SRC -c \"SELECT count(*) FROM crm.tickets WHERE subject = 'replicated back'\"" 20

echo "== after cutover: switch to sync, read your writes in the same transaction"
contains "sync allowed after cutover" "freshness sync" "$($ISO -c "SELECT isomer.alter_projection('account_view', freshness => 'sync')")"
coll=$($ISO -c "SELECT isomer._collection_table('crm', 'account_view')")
before=$($ISO -c "SELECT isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> 'open_tickets' FROM $coll WHERE isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> '_id' = '5'")
inside=$($ISO <<SQL
BEGIN;
INSERT INTO crm.tickets (account_id, subject) VALUES (5, 'sync check');
SELECT isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> 'open_tickets' FROM $coll WHERE isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> '_id' = '5';
COMMIT;
SQL
)
expect "a sync projection changes inside the writing transaction" "$((before + 1))" "$(echo "$inside" | tail -1)"

echo "== FR-P2/P3 sharding, and sync projections over co-located shards"
$ISO <<'SQL' >/dev/null
CREATE SCHEMA dist;
CREATE TABLE dist.customers (customer_id bigint PRIMARY KEY, name text, tier text);
CREATE TABLE dist.orders (order_id bigint, customer_id bigint NOT NULL, status text, total numeric, PRIMARY KEY (customer_id, order_id));
CREATE TABLE dist.plans (tier text PRIMARY KEY, discount numeric);
SELECT isomer.distribute(ARRAY['dist.customers', 'dist.orders']::regclass[], 'customer_id');
SELECT isomer.make_reference(ARRAY['dist.plans']::regclass[]);
INSERT INTO dist.plans VALUES ('gold', 0.1), ('silver', 0.05);
INSERT INTO dist.customers SELECT g, 'customer ' || g, CASE WHEN g % 2 = 0 THEN 'gold' ELSE 'silver' END FROM generate_series(1, 40) g;
INSERT INTO dist.orders SELECT g, 1 + g % 40, 'open', g * 10 FROM generate_series(1, 200) g;
SQL
expect "tables are co-located" "1" "$($ISO -c "SELECT count(DISTINCT colocationid) FROM pg_dist_partition WHERE logicalrelid IN ('dist.customers'::regclass, 'dist.orders'::regclass)")"
$ISO <<'SQL' >/dev/null
SELECT isomer.create_projection(
  name => 'customer_orders', kind => 'document', key => 'customer_id', database => 'dist', freshness => 'sync',
  query => $q$ SELECT c.customer_id, jsonb_build_object('name', c.name, 'tier', c.tier,
              'discount', (SELECT p.discount FROM dist.plans p WHERE p.tier = c.tier),
              'orders', coalesce((SELECT jsonb_agg(jsonb_build_object('id', o.order_id, 'status', o.status, 'total', o.total) ORDER BY o.order_id)
                                  FROM dist.orders o WHERE o.customer_id = c.customer_id), '[]'::jsonb)) AS doc
              FROM dist.customers c $q$,
  sources => '{"dist.customers": "customer_id", "dist.orders": "customer_id", "dist.plans": null}');
SQL
pass "sync projection over co-located shards accepted"
out=$($ISO -c "SELECT isomer.create_projection(name => 'by_order', kind => 'document', key => 'order_id', freshness => 'sync',
  query => 'SELECT o.order_id, jsonb_build_object(''status'', o.status) AS doc FROM dist.orders o', sources => '{\"dist.orders\": \"order_id\"}')" 2>&1 || true)
contains "sync refused when a source is sharded by another column" "is distributed by customer_id" "$out"
# Orders are spread as customer_id = 1 + order_id % 40, so customer 7's first order is 6.
$ISO -c "UPDATE dist.orders SET status = 'shipped' WHERE customer_id = 7 AND order_id = 6"
expect "sharded write reflected immediately" "shipped" \
  "$(mongo_eval 'print(db.getSiblingDB("dist").customer_orders.findOne({_id: 7}).orders.find(o => o.id === 6).status)')"

echo "== FR-C1 cache projection"
$ISO <<'SQL' >/dev/null
SELECT isomer.create_projection(
  name => 'open_order_count', kind => 'cache', key => 'customer_id', freshness => 'sync',
  query => $q$ SELECT c.customer_id, (SELECT count(*) FROM dist.orders o WHERE o.customer_id = c.customer_id AND o.status = 'open') AS value
              FROM dist.customers c $q$,
  sources => '{"dist.customers": "customer_id", "dist.orders": "customer_id"}', target_schema => 'dist');
SQL
expect "cache holds the precomputed value" "4" "$($ISO -c "SELECT isomer.cache_get('open_order_count', '7')")"
$ISO -c "UPDATE dist.orders SET status = 'shipped' WHERE customer_id = 7"
expect "cache updates with the write" "0" "$($ISO -c "SELECT value FROM dist.open_order_count WHERE customer_id = 7")"

echo "== FR-R3/R4/R5 read your writes on a bounded projection (SQL)"
$ISO <<'SQL' >/dev/null
SELECT isomer.create_projection(
  name => 'customer_brief', kind => 'document', key => 'customer_id', database => 'dist', lag => '2 seconds',
  query => $q$ SELECT c.customer_id, jsonb_build_object('name', c.name, 'tier', c.tier) AS doc FROM dist.customers c $q$,
  sources => '{"dist.customers": "customer_id"}');
SQL
coll=$($ISO -c "SELECT isomer._collection_table('dist', 'customer_brief')")
read_back=$($ISO <<SQL
UPDATE dist.customers SET name = 'renamed and read back' WHERE customer_id = 9;
SELECT isomer.wait_for(isomer.last_write_token(), 'customer_brief') IS NOT NULL;
SELECT isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> 'name' FROM $coll WHERE isomer._ejson_relax(documentdb_core.bson_to_json_string(document)::text::jsonb) ->> '_id' = '9';
SQL
)
expect "wait_for then read sees the write" "renamed and read back" "$(echo "$read_back" | tail -1)"
expect "freshness reports a token at least as new as the write" "t" \
  "$($ISO -c "SELECT isomer.freshness('customer_brief') >= (SELECT max(token) FROM isomer.pending) OR NOT EXISTS (SELECT 1 FROM isomer.pending)")"

echo "== FR-R4a read your writes through MongoDB drivers"
$ISO -c "SELECT cron.alter_job(jobid, active => false) FROM cron.job WHERE jobname = 'isomer-drain'" >/dev/null
sleep 2
tok=$($ISO -c "UPDATE dist.customers SET name = 'mongo ryw' WHERE customer_id = 11; SELECT t || ',' || i FROM isomer.token_to_mongo_timestamp(isomer.last_write_token())")
causal_read='const s = db.getMongo().startSession({causalConsistency: true});
s.advanceOperationTime(Timestamp({t: __T__, i: __I__}));
try { print(s.getDatabase("dist").customer_brief.findOne({_id: 11}).name) } catch (e) { print("ERR " + e.codeName + ": " + e.message) }'
causal_read=${causal_read//__T__/${tok%,*}}; causal_read=${causal_read//__I__/${tok#*,}}
contains "a causal read waits, then says 'not yet' while the projection is behind" "not yet" "$(mongo_eval "$causal_read")"
expect "a plain read returns the stale document" "customer 11" "$(mongo_eval 'print(db.getSiblingDB("dist").customer_brief.findOne({_id: 11}).name)')"
$ISO -c "SELECT cron.alter_job(jobid, active => true) FROM cron.job WHERE jobname = 'isomer-drain'" >/dev/null
expect "the same causal read succeeds once the projection catches up" "mongo ryw" "$(mongo_eval "$causal_read")"
contains "writes to a projection collection are refused" "read-only" \
  "$(mongo_eval 'try { db.getSiblingDB("dist").customer_brief.insertOne({_id: 999}); print("accepted") } catch (e) { print(e.message) }')"

echo "== non-superuser application role"
$ISO <<'SQL' >/dev/null
CREATE ROLE app LOGIN;
GRANT USAGE ON SCHEMA dist TO app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA dist TO app;
SQL
out=$($APP -c "BEGIN" -c "UPDATE dist.customers SET name = 'renamed by app' WHERE customer_id = 13" -c "SELECT isomer.wait_for(isomer.last_write_token(), 'customer_brief')" -c "ROLLBACK" 2>&1 || true)
contains "waiting inside the writing transaction is refused at once" "not committed yet" "$out"
expect "an application role's write maintains projections" "renamed by app" \
  "$($APP -c "UPDATE dist.customers SET name = 'renamed by app' WHERE customer_id = 13" -c "SELECT isomer.wait_for(isomer.last_write_token(), 'customer_brief') IS NOT NULL" >/dev/null; mongo_eval 'print(db.getSiblingDB("dist").customer_brief.findOne({_id: 13}).name)')"

echo "== FR-K1/K2/K3 the auditor"
# Several runs, spaced past the confirmation window, so a systematic false positive would show.
for _ in 1 2 3 4; do $ISO -c "SELECT isomer.audit(200)" >/dev/null; sleep 1; done
expect "no drift on healthy projections, across repeated audits" "0" "$($ISO -c "SELECT coalesce(sum(drift), 0) FROM isomer.drift_report")"
# Tamper with a document behind IsomerDB's back.
$ISO -c "SELECT documentdb_api.update('dist', '{\"update\": \"customer_orders\", \"updates\": [{\"q\": {\"_id\": 21}, \"u\": {\"\$set\": {\"name\": \"tampered\"}}}]}'::documentdb_core.bson)" >/dev/null
for _ in 1 2 3 4 5; do $ISO -c "SELECT isomer.audit(200)" >/dev/null; sleep 1; done
expect "drift detected and counted" "1" "$($ISO -c "SELECT drift FROM isomer.drift_report WHERE projection = 'customer_orders'")"
expect "the drifted input is pinned" "21|tampered" \
  "$($ISO -c "SELECT key || '|' || (actual ->> 'name') FROM isomer.drift_samples WHERE projection = 'customer_orders'")"
expect "drift raises an alert" "1" "$($ISO -c "SELECT count(*) FROM isomer.alerts WHERE alert = 'drift'")"
# Still wrong, audited again past the confirmation window: the same key isn't counted twice.
for _ in 1 2 3; do sleep 3; $ISO -c "SELECT isomer.audit(200)" >/dev/null; done
expect "a key that stays wrong is counted once" "1|1" \
  "$($ISO -c "SELECT (SELECT drift FROM isomer.drift_report WHERE projection = 'customer_orders') || '|' || (SELECT count(*) FROM isomer.drift_samples WHERE projection = 'customer_orders')")"
$ISO -c "SELECT isomer.repair('customer_orders')" >/dev/null
expect "repair restores the document" "customer 21" "$(mongo_eval 'print(db.getSiblingDB("dist").customer_orders.findOne({_id: 21}).name)')"
# Right again, then wrong again: that's new drift, and it counts.
for _ in 1 2; do $ISO -c "SELECT isomer.audit(200)" >/dev/null; sleep 1; done
$ISO -c "SELECT documentdb_api.update('dist', '{\"update\": \"customer_orders\", \"updates\": [{\"q\": {\"_id\": 21}, \"u\": {\"\$set\": {\"name\": \"tampered\"}}}]}'::documentdb_core.bson)" >/dev/null
for _ in 1 2 3; do $ISO -c "SELECT isomer.audit(200)" >/dev/null; sleep 3; done
expect "the same key drifting again after a repair counts again" "2" "$($ISO -c "SELECT drift FROM isomer.drift_report WHERE projection = 'customer_orders'")"
$ISO -c "SELECT isomer.repair('customer_orders')" >/dev/null
contains "drift report reads as a counter" "checks" "$($ISO -c "SELECT summary FROM isomer.drift_report WHERE projection = 'customer_orders'")"

echo "== phase 2 passed"
